def _build_required_removal(model: SchemaModel) -> list[MutationOperator]:
    out: list[MutationOperator] = []
    for entry in model.fields:
        if not entry.required_unconditionally:
            continue
        target = pointer(entry.path)
        out.append(
            MutationOperator(
                operator_id=f"remove_required_field@{target}",
                category=CATEGORY_REQUIRED_REMOVAL,
                target=target,
                expected_outcome=EXPECT_INVALID,
                steps=(MutationStep(OP_REMOVE, entry.path),),
                rationale="unconditionally required by the vendored schema",
            )
        )
    return out


def _build_optional_removal(model: SchemaModel) -> list[MutationOperator]:
    out: list[MutationOperator] = []
    for entry in model.fields:
        if entry.required_unconditionally or entry.required_conditionally:
            continue
        target = pointer(entry.path)
        out.append(
            MutationOperator(
                operator_id=f"remove_optional_field@{target}",
                category=CATEGORY_OPTIONAL_REMOVAL,
                target=target,
                expected_outcome=EXPECT_VALID,
                steps=(MutationStep(OP_REMOVE, entry.path),),
                rationale="declared but required by no schema branch",
            )
        )
    return out


def _build_emptiness(model: SchemaModel) -> list[MutationOperator]:
    out: list[MutationOperator] = []
    for entry in model.fields:
        if not entry.required_unconditionally:
            continue
        if len(entry.path) > _EMPTINESS_MAX_DEPTH or ARRAY_ITEM in entry.path:
            continue
        target = pointer(entry.path)
        for label, value in _EMPTINESS_VARIANTS:
            out.append(
                MutationOperator(
                    operator_id=f"set_{label}@{target}",
                    category=CATEGORY_EMPTINESS,
                    target=target,
                    expected_outcome=EXPECT_OBSERVE_ONLY,
                    steps=(MutationStep(OP_SET, entry.path, copy.deepcopy(value)),),
                    rationale=(
                        "absent / null / empty are distinct states the schema "
                        "does not resolve uniformly; behaviour is observed"
                    ),
                )
            )
    return out


def _build_type_violation(model: SchemaModel) -> list[MutationOperator]:
    out: list[MutationOperator] = []
    for entry in model.fields:
        target = pointer(entry.path)
        if entry.types:
            replacement: Any = None
            found = False
            for json_type, candidate in _TYPE_CANDIDATES:
                if not _type_permitted(json_type, entry.types):
                    replacement = copy.deepcopy(candidate)
                    found = True
                    break
            if found:
                out.append(
                    MutationOperator(
                        operator_id=f"violate_type@{target}",
                        category=CATEGORY_TYPE,
                        target=target,
                        expected_outcome=EXPECT_INVALID,
                        steps=(MutationStep(OP_SET, entry.path, replacement),),
                        rationale=(
                            "replacement JSON type is outside the declared "
                            f"type(s) {','.join(entry.types)}"
                        ),
                    )
                )
        if entry.array_of_objects:
            out.append(
                MutationOperator(
                    operator_id=f"violate_nested_structure@{target}",
                    category=CATEGORY_TYPE,
                    target=target,
                    expected_outcome=EXPECT_INVALID,
                    steps=(
                        MutationStep(OP_SET, entry.path, [_SYNTHETIC_NESTED_ITEM]),
                    ),
                    rationale="array of objects given a scalar element",
                )
            )
    return out


def _build_enum_violation(model: SchemaModel) -> list[MutationOperator]:
    out: list[MutationOperator] = []
    for entry in model.fields:
        if not entry.enum:
            continue
        target = pointer(entry.path)
        out.append(
            MutationOperator(
                operator_id=f"violate_enum@{target}",
                category=CATEGORY_ENUM,
                target=target,
                expected_outcome=EXPECT_INVALID,
                steps=(MutationStep(OP_SET, entry.path, _SYNTHETIC_ENUM_TOKEN),),
                rationale="token outside the schema's declared vocabulary",
            )
        )
        # The near miss is the operator that matters: a validator that guessed
        # the intended term, or auto-corrected it, would pass the obvious case
        # and fail here.
        first = entry.enum[0]
        if isinstance(first, str) and len(first) > 1:
            near = first[:-1]
            if near and near not in entry.enum:
                out.append(
                    MutationOperator(
                        operator_id=f"violate_enum_near_miss@{target}",
                        category=CATEGORY_ENUM,
                        target=target,
                        expected_outcome=EXPECT_INVALID,
                        steps=(MutationStep(OP_SET, entry.path, near),),
                        rationale=(
                            "one character short of a permitted term; must be "
                            "rejected, never corrected to the nearest match"
                        ),
                    )
                )
    return out


def _build_unknown_field(model: SchemaModel) -> list[MutationOperator]:
    out: list[MutationOperator] = []
    for location in model.objects:
        target = pointer(location.path)
        out.append(
            MutationOperator(
                operator_id=f"add_unknown_field@{target}",
                category=CATEGORY_UNKNOWN_FIELD,
                target=target,
                # Read off the schema per location, not assumed globally.
                expected_outcome=EXPECT_INVALID if location.closed else EXPECT_VALID,
                steps=(
                    MutationStep(OP_INSERT_KEY, location.path, _SYNTHETIC_UNKNOWN_KEY),
                ),
                rationale=(
                    "additionalProperties is false here"
                    if location.closed
                    else "this location is open by design"
                ),
            )
        )
    return out


#: Bound for category L. At most 6 + 4 = 10 operators are generated: pairs drawn
#: from the first four root-level required fields (C(4,2) = 6) and four
#: required-removal × enum-violation pairs. The full product of the ~700
#: single-step operators is deliberately NOT explored: combination coverage adds
#: no new failure mode here, only runtime.
_COMBINED_REQUIRED_HEAD = 4
_COMBINED_ENUM_PAIRS = 4


def _build_combined_operators(model: SchemaModel) -> list[MutationOperator]:
    root_required = [
        entry
        for entry in model.fields
        if entry.required_unconditionally and len(entry.path) == 1
    ][:_COMBINED_REQUIRED_HEAD]
    enum_fields = [entry for entry in model.fields if entry.enum][
        : _COMBINED_ENUM_PAIRS + _COMBINED_REQUIRED_HEAD
    ]

    out: list[MutationOperator] = []
    for i, left in enumerate(root_required):
        for right in root_required[i + 1 :]:
            target = f"{pointer(left.path)},{pointer(right.path)}"
            out.append(
                MutationOperator(
                    operator_id=f"remove_two_required_fields@{target}",
                    category=CATEGORY_COMBINED,
                    target=target,
                    expected_outcome=EXPECT_INVALID,
                    steps=(
                        MutationStep(OP_REMOVE, left.path),
                        MutationStep(OP_REMOVE, right.path),
                    ),
                    rationale="two simultaneous required-field removals",
                )
            )

    paired = 0
    for entry in enum_fields:
        if paired >= _COMBINED_ENUM_PAIRS:
            break
        # Pick a required field that does not overlap the enum target.
        partner = next(
            (
                candidate
                for candidate in root_required
                if candidate.path != entry.path[: len(candidate.path)]
            ),
            None,
        )
        if partner is None:
            continue
        target = f"{pointer(partner.path)},{pointer(entry.path)}"
        out.append(
            MutationOperator(
                operator_id=f"remove_required_and_violate_enum@{target}",
                category=CATEGORY_COMBINED,
                target=target,
                expected_outcome=EXPECT_INVALID,
                steps=(
                    MutationStep(OP_REMOVE, partner.path),
                    MutationStep(OP_SET, entry.path, _SYNTHETIC_ENUM_TOKEN),
                ),
                rationale="a required-field removal plus a vocabulary violation",
            )
        )
        paired += 1
    return out


def build_operators(root: Path) -> tuple[MutationOperator, ...]:
    """Build the full deterministic operator catalog from the vendored schema.

    Sorted by ``operator_id`` so the trial order never depends on dict
    iteration, schema key order, or anything else that could drift.
    """
    model = introspect_schema(root)
    operators: list[MutationOperator] = []
    operators += _build_required_removal(model)
    operators += _build_optional_removal(model)
    operators += _build_emptiness(model)
    operators += _build_type_violation(model)
    operators += _build_enum_violation(model)
    operators += _build_unknown_field(model)
    operators += _build_combined_operators(model)

    seen: set[str] = set()
    unique: list[MutationOperator] = []
    for operator in sorted(operators, key=lambda op: op.operator_id):
        if operator.operator_id in seen:
            continue
        seen.add(operator.operator_id)
        unique.append(operator)
    return tuple(unique)


