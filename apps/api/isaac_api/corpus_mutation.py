#: Path-template segment standing for "an item of this array". Resolved to
#: index 0 and only index 0 — a bounded, deterministic choice. Sweeping every
#: index would multiply the trial count by record content, which is both slow
#: and (over a real corpus) a per-record disclosure.
ARRAY_ITEM = "*"

CATEGORY_REQUIRED_REMOVAL = "A_required_field_removal"
CATEGORY_OPTIONAL_REMOVAL = "C_optional_field_removal"
CATEGORY_EMPTINESS = "D_null_empty_missing"
CATEGORY_TYPE = "E_type_violation"
CATEGORY_ENUM = "F_enum_violation"
CATEGORY_UNKNOWN_FIELD = "G_unknown_field"
CATEGORY_COMBINED = "L_multiple_simultaneous"

#: The record must become invalid.
EXPECT_INVALID = "record_becomes_schema_invalid"
#: The record must stay valid (and, for category C, gain no `required` error).
EXPECT_VALID = "record_stays_schema_valid"
#: The schema does not specify one answer; the harness records what happened and
#: asserts nothing about validity. Used only by category D.
EXPECT_OBSERVE_ONLY = "outcome_observed_not_asserted"

