@dataclass(frozen=True)
class Evaluation:
    """One structured validation result, comparable for equality and order."""

    schema_valid: bool
    error_count: int
    rule_families: tuple[str, ...]
    schema_paths: tuple[str, ...]
    #: Ordered per-diagnostic identity. Order is significant.
    signature: tuple[tuple[str, str, str, str, bool], ...]
    #: True when `validate_official` and `diagnose` disagree about validity.
    engines_disagree: bool

    @property
    def unordered(self) -> frozenset[tuple[str, str, str, str, bool]]:
        return frozenset(self.signature)


def evaluate(record: Mapping[str, Any], root: Path) -> Evaluation:
    """Run BOTH engines over ``record`` and structure the result.

    ``validate_official`` decides ``schema_valid`` (it is the authority);
    ``diagnose`` supplies the machine-comparable detail. They are cross-checked
    rather than assumed to agree — a disagreement between two views of the same
    schema is exactly the kind of defect this harness exists to surface.
    """
    official = validate_official(dict(record), Path(root))
    report = diagnose(dict(record), Path(root))
    signature = tuple(
        (d.pointer, d.rule_family, d.kind, d.message, d.conditional)
        for d in report.diagnostics
    )
    return Evaluation(
        schema_valid=official.ok,
        error_count=len(report.diagnostics),
        rule_families=tuple(sorted({d.rule_family for d in report.diagnostics})),
        schema_paths=tuple(sorted({d.schema_pointer for d in report.diagnostics})),
        signature=signature,
        engines_disagree=official.ok != report.ok,
    )


def check_repeatability(evaluations: Sequence[Evaluation]) -> bool:
    """True when every run produced the same *set* of diagnostics.

    Deliberately unordered: an ordering difference is reported by
    :func:`check_ordering_stable` instead, so an ordering bug is never misfiled
    as a content bug.
    """
    if not evaluations:
        return False
    first = evaluations[0]
    return all(
        item.schema_valid == first.schema_valid
        and item.error_count == first.error_count
        and item.rule_families == first.rule_families
        and item.schema_paths == first.schema_paths
        and item.unordered == first.unordered
        for item in evaluations
    )


def check_ordering_stable(evaluations: Sequence[Evaluation]) -> bool:
    """True when every run produced the diagnostics in the same ORDER."""
    if not evaluations:
        return False
    first = evaluations[0].signature
    return all(item.signature == first for item in evaluations)


def _required_pointers(evaluation: Evaluation) -> frozenset[str]:
    return frozenset(
        item[0] for item in evaluation.signature if item[1] == "required"
    )


def _workflow_consistent(schema_valid: bool) -> bool:
    """A schema-invalid record must never reach the ``export`` step.

    Narrow on purpose. ``derive_workflow`` is a pure function of its arguments,
    so this asserts the one property that connects validation truth to the
    workflow the UI shows: an invalid record cannot present ``export`` as the
    current step, and cannot show ``export`` as completed.

    **THIS IS NOT A PER-TRIAL ORACLE, and the report's counter name overstates
    it.** It takes a single boolean and calls a pure function; it never sees the
    record, the mutation, or the clone. Over N trials it can therefore only be
    all-zero or all-N — it is a ``derive_workflow`` regression check evaluated
    once per trial, not an independent per-trial observation like
    ``source_unchanged`` or ``restoration``. It is retained because the property
    it checks is worth pinning, and named here so nobody reads
    ``workflow_consistency_failures: 0`` as 3111 independent confirmations.
    """
    derived = derive_workflow(
        pending_count=0,
        draft_ok=schema_valid,
        ready=schema_valid,
        exported=False,
        rev=1,
    )
    steps = {step["id"]: step for step in derived["ordered_steps"]}
    if steps["export"]["state"] == "completed":
        return False
    if schema_valid:
        return derived["current_step"] == "export"
    return derived["current_step"] not in (None, "export")


