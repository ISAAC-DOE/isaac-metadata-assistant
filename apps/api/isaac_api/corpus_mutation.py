@dataclass(frozen=True)
class MutationStep:
    """One elementary edit. Data, not a closure — comparable and printable."""

    op_kind: str
    #: For ``remove``/``set``: the path of the value itself. For ``insert_key``:
    #: the path of the PARENT object.
    path: tuple[str, ...]
    #: ``set``: the replacement value. ``insert_key``: the key name to insert.
    payload: Any = None

    def __post_init__(self) -> None:
        if self.op_kind not in (OP_REMOVE, OP_SET, OP_INSERT_KEY):
            raise ValueError(f"unknown mutation step kind: {self.op_kind!r}")
        if self.op_kind == OP_REMOVE and self.path and self.path[-1] == ARRAY_ITEM:
            # Refused structurally rather than left as a latent trap. `del l[0]`
            # shifts every later element up, so the targeted undo — which writes
            # back by index — would overwrite a sibling instead of re-inserting.
            # No catalog operator does this today; this makes it impossible for
            # one to start.
            raise ValueError(
                "removing an array item is unsupported: the targeted undo "
                "cannot re-insert at an index without shifting siblings"
            )

    def resolve(self, record: Any) -> tuple[Any, ...] | None:
        """Concrete path this step would act on, or ``None`` if inapplicable."""
        if self.op_kind == OP_INSERT_KEY:
            resolved = _resolve(self.path, record)
            if resolved is None:
                return None
            concrete, node = resolved
            if not isinstance(node, dict) or self.payload in node:
                return None
            return concrete
        if self.op_kind in (OP_REMOVE, OP_SET):
            if not self.path:
                return None
            parent = _resolve(self.path[:-1], record)
            if parent is None:
                return None
            parent_concrete, parent_node = parent
            last = self.path[-1]
            if last == ARRAY_ITEM:
                if not isinstance(parent_node, list) or not parent_node:
                    return None
                return parent_concrete + (0,)
            if not isinstance(parent_node, dict) or last not in parent_node:
                return None
            return parent_concrete + (last,)
        raise ValueError(f"unknown mutation step kind: {self.op_kind!r}")


@dataclass(frozen=True)
class MutationOperator:
    """One mutation: what it targets, what it does, what should happen.

    ``apply`` never modifies its argument. Subclasses may override ``apply`` —
    the test suite does exactly that to prove the oracles can fail — but a
    subclass whose behaviour departs from its declared ``steps`` will be caught
    by the restoration oracle, which undoes the declared steps individually.
    """

    operator_id: str
    category: str
    #: JSON-Pointer-shaped target against the PUBLIC schema (``*`` for an item),
    #: or a comma-joined list for a combined operator.
    target: str
    expected_outcome: str
    steps: tuple[MutationStep, ...]
    rationale: str = ""

    def applicability(self, record: Mapping[str, Any]) -> bool:
        """Can this mutation be applied to ``record``?

        Every step must resolve, and no two steps may act on overlapping paths —
        an overlap would make the targeted undo ambiguous.
        """
        resolved: list[tuple[Any, ...]] = []
        for step in self.steps:
            concrete = step.resolve(record)
            if concrete is None:
                return False
            resolved.append(concrete)
        for i, left in enumerate(resolved):
            for right in resolved[i + 1 :]:
                shorter, longer = sorted((left, right), key=len)
                if longer[: len(shorter)] == shorter:
                    return False
        return True

    def apply(self, record: Mapping[str, Any]) -> dict:
        """Return a MUTATED DEEP CLONE. The input is never modified."""
        clone = copy.deepcopy(dict(record))
        for step in self.steps:
            concrete = step.resolve(record)
            if concrete is None:
                raise ValueError(
                    f"operator {self.operator_id!r} is not applicable to this record"
                )
            if step.op_kind == OP_REMOVE:
                del _node_at(clone, concrete[:-1])[concrete[-1]]
            elif step.op_kind == OP_SET:
                _node_at(clone, concrete[:-1])[concrete[-1]] = copy.deepcopy(
                    step.payload
                )
            elif step.op_kind == OP_INSERT_KEY:
                _node_at(clone, concrete)[step.payload] = _SYNTHETIC_STRING
            else:  # pragma: no cover - guarded in MutationStep.resolve
                raise ValueError(f"unknown mutation step kind: {step.op_kind!r}")
        return clone


