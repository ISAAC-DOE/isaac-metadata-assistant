"""Deterministic mutation-testing harness for the official-schema validator.

WHAT THIS IS
============
A pure-logic library that takes a corpus of official ISAAC records, applies a
catalog of controlled deterministic mutations to **deep clones** of them, runs
the authoritative validator (:func:`isaac_records.official.validate_official`)
and the normalization layer (:func:`isaac_records.diagnostics.diagnose`) over
each clone, and reports whether the observed outcome matched the outcome the
**public vendored schema** predicts.

It answers a question the existing test suite does not: *is ISAAC's validation
behaviour deterministic, side-effect-free, non-guessing and reversible under
controlled perturbation?* — as opposed to *does this one fixture pass?*

WHAT THIS IS NOT
================
* **Database-free.** This module opens no connection, imports no driver, reads
  no credential and knows no hostname. It is driven entirely by records the
  caller hands it. This is a statement about THIS MODULE, not about the
  deployment: ``db_recon.py`` does connect, from the pod. The real-corpus runner
  (the 30 production-derived records in the
  SLAC Postgres) is **BLOCKED** pending Dean's answer to Q19 — see
  ``docs/superpowers/plans/2026-08-02-corpus-validation-authorization.md`` §8.
  Do not add a database caller here; add nothing that could become one.
* **No FastAPI, no route, no network, no filesystem write.** The only file this
  module causes to be read is the vendored schema, and only indirectly, through
  ``isaac_records.official``.
* **Not part of the truth path.** It *consumes* the validator. It never
  reimplements a rule, never decides validity itself, and never writes to
  ``src/`` or ``schema/``. Every expectation it holds is derived by reading
  ``schema/isaac_record_v1.json`` at run time — there is no hand-written list of
  required fields, types or enums anywhere below.
* **No clock, no randomness.** Nothing in any compared or reported value comes
  from ``datetime.now()`` or ``random``. Operator order is a deterministic sort
  on ``operator_id``.

Style precedent: ``apps/api/isaac_api/db_recon.py`` — pure logic, importable,
no FastAPI, fully unit-testable, sanitized output projected through frozen
key allowlists.

MUTATION CATEGORIES IMPLEMENTED
===============================
Every operator below is generated by walking the vendored schema. Letters match
the category taxonomy used in the authorizing plan.

* **A — required-field removal.** One operator per *unconditionally* required
  field (a name in an object subschema's own ``required`` list, reached only by
  descending ``properties``/``items``). Fields required only under
  ``if``/``then``/``else`` are deliberately excluded: their applicability is a
  fact about the record's content, not about the schema (see the "conditional"
  discussion in ``diagnostics.py`` and §4 of the authorization audit).
  Expectation: the record becomes schema-invalid.
* **C — optional-field removal.** One operator per declared property that is
  neither unconditionally nor conditionally required anywhere. Expectation: the
  record stays valid **and** no ``required``-family diagnostic appears that was
  not already in the baseline.
* **D — null / empty / missing distinctions.** ``null``, ``""``, whitespace-only,
  ``[]`` and ``{}`` substituted for a bounded set of required fields (depth ≤ 2,
  no array-item templates). These are **observation-only**: the schema does not
  specify a single answer for every field, so the harness records what the
  engine does rather than asserting a behaviour. ("Absent" is category A.)
* **E — type violations.** The replacement value is chosen deterministically as
  the first candidate in a fixed list whose JSON type is *not* permitted by the
  field's declared ``type``, so string↔number, object↔scalar and scalar↔array
  all fall out of one rule rather than a hand-written table. A second operator
  replaces an array-of-objects with an array holding a scalar element (invalid
  nested structure). Expectation: invalid.
* **F — enum / vocabulary violations.** Two operators per schema ``enum``: an
  obviously-synthetic token, and a **near miss** (the first permitted value with
  its last character removed). The near miss is the one that matters — it is
  what would catch a validator that guessed the intended value or silently
  auto-corrected it. Expectation: invalid, and the mutated value is still the
  token we wrote after validation.
* **G — unknown / additional fields.** An unknown key inserted at the root and
  at every declared object location. The expectation is **read off the schema
  per location**: ``additionalProperties: false`` ⇒ invalid; anything else ⇒
  valid. The vendored v1.05 schema is closed in 37 places and open in ~14, so
  both branches are genuinely exercised.
* **L — multiple simultaneous mutations.** Bounded, representative
  combinations, **not** the full product. The bound is stated at
  :func:`_build_combined_operators`: at most 10 operators — 6 pairs drawn from
  the first four root-level required fields, plus 4 required-removal ×
  enum-violation pairs. Expectation: invalid, with at least two distinct
  diagnostic pointers.

NOT YET IMPLEMENTED, AND WHY
============================
Categories **B, H, I, J and K** are deliberately absent. This is an omission
with a reason, not an oversight:

* **B — conditional-required removal.** Whether an ``if``/``then`` rule fires
  depends on the record's own content, so applicability is record-derived rather
  than schema-derived. Over a real corpus that makes it a field-presence
  disclosure (authorization audit §3–§4). It is implementable safely over public
  fixtures, but building it here would create a runner whose only missing piece
  is the corpus — exactly what §8 says not to build. Deferred with Q19.
* **H — evidence removal** and **I — confirmation removal.** ``evidence`` and
  ``needs_confirmation`` live in the **draft envelope**
  (``src/isaac_records/draft_validator.py``), not in the official record. The
  official schema has no evidence wrapper at all — ``CLAUDE.md`` §4 is explicit
  that official records "avoid custom evidence envelopes". There is nothing to
  remove from an official record, so these categories belong to a draft-level
  harness, not this one. (They are also named as NOT SAFE in the audit §4.)
* **J — provenance mutation.** Provenance in this project lives in the evidence
  **sidecar** (``records/<ULID>.evidence.json``), which the official schema does
  not describe. Same reason as H/I: out of this schema's scope.
* **K — cross-field consistency.** The official schema encodes exactly four
  cross-field rules, all of them ``if``/``then`` — i.e. category B. Anything
  beyond them would be a scientific-consistency judgement, which ``CLAUDE.md``
  §3 confines to the advisory review tier and forbids from asserting validity.
  Implementing K here would mean inventing rules the schema does not state,
  which is a no-guessing violation.

ORACLES
=======
The harness does not merely ask "did the validator throw". Per trial:

``schema_valid``          from :func:`validate_official`, cross-checked against
                          :func:`diagnose` (a disagreement is a reported finding).
``error_count`` / families / schema paths, from :func:`diagnose`.
``source_unchanged``      the input record is byte-identical (canonical JSON)
                          before and after ``apply``, **and** shares no mutable
                          container with the returned clone. This is the single
                          most important oracle: it catches accidental shared
                          state, the failure mode that silently corrupts every
                          later trial.
``restoration``           the declared mutation steps are undone **individually**
                          (not by wholesale replacement), and both the record
                          content and the evaluation must return to baseline. A
                          targeted undo is what makes this failable: an operator
                          whose ``apply`` does something its declared steps do
                          not describe will not restore.
``repeatability``         N identical structured results (N=3 by default).
``ordering_stable``       identical *order*, not merely the same multiset —
                          reported separately from repeatability so an ordering
                          bug is not misfiled as a content bug.
``no_guessing``           the validator populates nothing: a removed path is
                          still absent, a substituted value is still exactly what
                          was written, and the clone is byte-identical before and
                          after validation.
``workflow_consistency``  a narrow invariant on
                          :func:`isaac_api.workflow.derive_workflow`: a
                          schema-invalid record can never reach the ``export``
                          step.

REPORT
======
:func:`build_report` emits **global scalar counts only**, projected key-by-key
through frozen allowlists, mirroring the ``_DB_RECON_*`` pattern in
``routes.py``. There is deliberately no per-operator, per-record or per-path
breakdown: whether a mutation is *applicable* to a record is a fact about that
record's structure, and a per-operator applicability table is a field-presence
map over the corpus (authorization audit §3).

**THIS SHAPE IS NOT YET SAFE FOR THE REAL CORPUS, and an earlier version of this
docstring wrongly said it was "reusable unchanged".** Audit §4 authorizes only
total trials run, ONE global `outcomes_matched` **boolean**, and
`determinism_failures` with a *refusal to elaborate* when nonzero. This module
serves five mutation counts and seven oracle counts, with no refusal path. Over
a 30-row corpus `restoration_failures: 1` is exactly the single-record
structural fact §4.3.1 forbids, and `trials_applicable` is the global sum of the
field-presence map — dominated by the optional-field categories §4 lists as NOT
SAFE.

That is harmless here (10 public fixtures, no route, no caller) and must be
closed BEFORE any corpus is attached, not after. See the "not yet implemented"
section below.
"""

