#: type the field does not permit is used, so the concrete swap (string→number,
#: object→scalar, scalar→array, ...) is derived from the schema rather than
#: enumerated by hand.
_TYPE_CANDIDATES: tuple[tuple[str, Any], ...] = (
    ("string", _SYNTHETIC_STRING),
    ("integer", _SYNTHETIC_NUMBER),
    ("array", list(_SYNTHETIC_ARRAY)),
    ("object", {_SYNTHETIC_OBJECT_KEY: _SYNTHETIC_STRING}),
    ("boolean", True),
)

