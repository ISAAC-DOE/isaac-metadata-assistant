@dataclass(frozen=True)
class HarnessResult:
    """Internal, rich result. See :func:`build_report` for what may be served."""

    records_scanned: int
    records_passing_baseline: int
    records_failing_baseline: int
    operators_defined: int
    trials: tuple[TrialOutcome, ...] = ()
    schema_fingerprint: str = ""

    @property
    def applicable_trials(self) -> tuple[TrialOutcome, ...]:
        return tuple(t for t in self.trials if t.applicable)

    def oracle_failures(self, label: str) -> tuple[TrialOutcome, ...]:
        return tuple(t for t in self.trials if label in t.oracle_failures)

    @property
    def unexpected(self) -> tuple[TrialOutcome, ...]:
        return tuple(t for t in self.trials if t.outcome_matched is False)


def run_harness(
    records: Iterable[Mapping[str, Any]],
    root: Path,
    *,
    operators: Sequence[MutationOperator] | None = None,
    repeat: int = 3,
) -> HarnessResult:
    """Run every operator against every record.

    ``records`` is supplied by the caller: this module deliberately knows no
    corpus location, so it cannot grow a database or fixture dependency by
    accident.
    """
    root = Path(root)
    catalog = tuple(operators) if operators is not None else build_operators(root)
    corpus = [dict(record) for record in records]

    passing = 0
    trials: list[TrialOutcome] = []
    for record in corpus:
        baseline = evaluate(record, root)
        if baseline.schema_valid:
            passing += 1
        for operator in catalog:
            # Per-trial fail-closed. A pathological operator that raises would
            # otherwise abort the whole sweep and produce NO report at all --
            # fail-closed was designed (see `build_failure_report`) but not
            # wired, which review proved by making an operator raise `KeyError`
            # straight out of `run_trial`. A raising operator is now recorded as
            # one unexpected outcome and the sweep continues; the exception is
            # NOT stored, because its text could carry a record value.
            try:
                trials.append(
                    run_trial(record, operator, root, baseline=baseline, repeat=repeat)
                )
            except (KeyboardInterrupt, SystemExit):
                raise
            except BaseException:  # noqa: BLE001 - must never leak, must never abort
                trials.append(
                    TrialOutcome(
                        operator_id=operator.operator_id,
                        category=operator.category,
                        expected_outcome=operator.expected_outcome,
                        applicable=True,
                        outcome_matched=False,
                    )
                )

    return HarnessResult(
        records_scanned=len(corpus),
        records_passing_baseline=passing,
        records_failing_baseline=len(corpus) - passing,
        operators_defined=len(catalog),
        trials=tuple(trials),
        schema_fingerprint=schema_fingerprint(root),
    )


