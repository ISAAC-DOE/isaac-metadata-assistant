@dataclass(frozen=True)
class SchemaField:
    """One property declared by the vendored schema, at one location."""

    #: Instance path template, ``*`` for an array item.
    path: tuple[str, ...]
    name: str
    #: In its parent object subschema's own ``required`` list.
    required_unconditionally: bool
    #: Required only under an ``if``/``then``/``else`` (or other combinator).
    required_conditionally: bool
    #: Declared JSON types; empty when the subschema declares none.
    types: tuple[str, ...]
    #: Declared ``enum``, or ``None``.
    enum: tuple[Any, ...] | None
    #: True when this field is an array whose items are objects.
    array_of_objects: bool


@dataclass(frozen=True)
class SchemaObject:
    """One object location declared by the vendored schema."""

    path: tuple[str, ...]
    #: ``additionalProperties: false`` — an unknown key here is a hard failure.
    closed: bool
    declared: tuple[str, ...]


@dataclass(frozen=True)
class SchemaModel:
    fields: tuple[SchemaField, ...]
    objects: tuple[SchemaObject, ...]
    #: Instance paths that some ``then``/``else``/combinator branch requires.
    conditional_required: frozenset[tuple[str, ...]]
    #: Root-level unconditionally required names, in schema declaration order.
    root_required: tuple[str, ...]


def _collect_conditional_required(
    node: Any, path: tuple[str, ...], out: set[tuple[str, ...]]
) -> None:
    """Collect instance paths required by a conditional/combinator branch.

    An ``if`` subschema is deliberately NOT descended: its ``required`` states a
    *condition* for the rule to fire, not a requirement on the record. Treating
    it as a requirement would wrongly move ``context`` out of the optional set
    (v1.05's ``allOf[1].if`` lists it), losing real coverage.
    """
    if not isinstance(node, Mapping):
        return
    for name in node.get("required", ()) or ():
        if isinstance(name, str):
            out.add(path + (name,))
    for prop_name, sub in (node.get("properties") or {}).items():
        _collect_conditional_required(sub, path + (prop_name,), out)
    items = node.get("items")
    if items is not None:
        _collect_conditional_required(items, path + (ARRAY_ITEM,), out)


def _walk_branches(node: Any, path: tuple[str, ...], out: set[tuple[str, ...]]) -> None:
    """Find every conditional branch anywhere in the schema and harvest it."""
    if not isinstance(node, Mapping):
        return
    for keyword in _APPLY_KEYWORDS:
        if keyword in node:
            _collect_conditional_required(node[keyword], path, out)
    for keyword in _BRANCH_KEYWORDS:
        for member in node.get(keyword, ()) or ():
            _walk_branches(member, path, out)
            # A combinator member that is itself a plain schema still states
            # requirements that are not unconditional at `path`.
            _collect_conditional_required(member, path, out)
    for prop_name, sub in (node.get("properties") or {}).items():
        _walk_branches(sub, path + (prop_name,), out)
    items = node.get("items")
    if items is not None:
        _walk_branches(items, path + (ARRAY_ITEM,), out)


def _walk_structure(
    node: Any,
    path: tuple[str, ...],
    conditional: frozenset[tuple[str, ...]],
    fields: list[SchemaField],
    objects: list[SchemaObject],
) -> None:
    """Descend ONLY ``properties``/``items`` — the unconditional structure."""
    if not isinstance(node, Mapping):
        return
    properties = node.get("properties") or {}
    if node.get("type") == "object" or properties:
        objects.append(
            SchemaObject(
                path=path,
                closed=node.get("additionalProperties") is False,
                declared=tuple(properties),
            )
        )
    required = tuple(node.get("required", ()) or ())
    for prop_name, sub in properties.items():
        sub_path = path + (prop_name,)
        declared_type = sub.get("type") if isinstance(sub, Mapping) else None
        if isinstance(declared_type, str):
            types: tuple[str, ...] = (declared_type,)
        elif isinstance(declared_type, list):
            types = tuple(str(t) for t in declared_type)
        else:
            types = ()
        raw_enum = sub.get("enum") if isinstance(sub, Mapping) else None
        items = sub.get("items") if isinstance(sub, Mapping) else None
        fields.append(
            SchemaField(
                path=sub_path,
                name=prop_name,
                required_unconditionally=prop_name in required,
                required_conditionally=sub_path in conditional,
                types=types,
                enum=tuple(raw_enum) if isinstance(raw_enum, list) else None,
                array_of_objects=bool(
                    types == ("array",)
                    and isinstance(items, Mapping)
                    and (items.get("type") == "object" or "properties" in items)
                ),
            )
        )
        _walk_structure(sub, sub_path, conditional, fields, objects)
    items = node.get("items")
    if items is not None:
        _walk_structure(items, path + (ARRAY_ITEM,), conditional, fields, objects)


def introspect_schema(root: Path) -> SchemaModel:
    """Read the vendored schema and derive the mutation model from it.

    The schema document is read through ``isaac_records.official.schema_path``
    so there is exactly one notion of "the authoritative schema" in the process.
    Nothing about required fields, types or enums is written down in this module.
    """
    document = json.loads(schema_path(Path(root)).read_text(encoding="utf-8"))

    conditional: set[tuple[str, ...]] = set()
    _walk_branches(document, (), conditional)

    fields: list[SchemaField] = []
    objects: list[SchemaObject] = []
    _walk_structure(document, (), frozenset(conditional), fields, objects)

    return SchemaModel(
        fields=tuple(fields),
        objects=tuple(objects),
        conditional_required=frozenset(conditional),
        root_required=tuple(document.get("required", ()) or ()),
    )


# --------------------------------------------------------------------------
# Path resolution
# --------------------------------------------------------------------------


def _resolve(template: Sequence[Any], record: Any) -> tuple[tuple[Any, ...], Any] | None:
    """Resolve a path template against a record.

    Returns ``(concrete_path, node)`` or ``None`` when any segment is absent.
    ``*`` resolves to index 0 of a non-empty list; an empty list is unresolvable
    (and therefore the operator is simply not applicable to that record).
    """
    node = record
    concrete: list[Any] = []
    for segment in template:
        if segment == ARRAY_ITEM:
            if not isinstance(node, list) or not node:
                return None
            concrete.append(0)
            node = node[0]
        elif isinstance(node, dict) and segment in node:
            concrete.append(segment)
            node = node[segment]
        else:
            return None
    return tuple(concrete), node


def _node_at(record: Any, concrete: Sequence[Any]) -> Any:
    node = record
    for segment in concrete:
        node = node[segment]
    return node


