# Canonical serialization
# --------------------------------------------------------------------------


def canonical(value: Any) -> str:
    """Deterministic JSON rendering used for every byte-identity comparison.

    ``sort_keys=True`` so that a change of key *order* is not reported as a
    change of content; a mutation that only reorders keys is not a mutation of
    the record's meaning.
    """
    return json.dumps(value, sort_keys=True, separators=(",", ":"), ensure_ascii=False)


def _json_type(value: Any) -> str:
    if value is None:
        return "null"
    if isinstance(value, bool):  # bool before int: bool is an int subclass
        return "boolean"
    if isinstance(value, int):
        return "integer"
    if isinstance(value, float):
        return "number"
    if isinstance(value, str):
        return "string"
    if isinstance(value, list):
        return "array"
    if isinstance(value, dict):
        return "object"
    raise TypeError(f"not a JSON value: {type(value).__name__}")


def _type_permitted(json_type: str, declared: Sequence[str]) -> bool:
    """Is ``json_type`` acceptable where ``declared`` types are allowed?

    ``integer`` satisfies a declared ``number`` (JSON Schema's numeric tower);
    the reverse does not hold and is not assumed.
    """
    if json_type in declared:
        return True
    return json_type == "integer" and "number" in declared


def _container_ids(value: Any, out: set[int]) -> None:
    if isinstance(value, dict):
        out.add(id(value))
        for item in value.values():
            _container_ids(item, out)
    elif isinstance(value, list):
        out.add(id(value))
        for item in value:
            _container_ids(item, out)


def shares_container(left: Any, right: Any) -> bool:
    """True if ``left`` and ``right`` share any mutable container by identity.

    A shallow copy passes a naive "the top-level objects differ" check while
    still aliasing every nested dict, so mutating the clone silently mutates the
    source. This catches that before it can corrupt a later trial.
    """
    left_ids: set[int] = set()
    right_ids: set[int] = set()
    _container_ids(left, left_ids)
    _container_ids(right, right_ids)
    return bool(left_ids & right_ids)


def pointer(segments: Sequence[Any]) -> str:
    """Render a path template as a JSON-Pointer-shaped string (``*`` retained)."""
    if not segments:
        return "/"
    return "".join(
        "/" + str(seg).replace("~", "~0").replace("/", "~1") for seg in segments
    )


