OP_SET = "set"
OP_INSERT_KEY = "insert_key"

# Obviously-synthetic payloads. Every one is a compile-time constant: nothing
# here is derived from a record, so no mutated value can carry record content.
_SYNTHETIC_STRING = "SYNTHETIC_INVALID_TYPE_VALUE_ZZ9"
_SYNTHETIC_NUMBER = -987654321
