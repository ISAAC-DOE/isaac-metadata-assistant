#: Oracle failure labels. Stable strings so a caller can group without parsing.
ORACLE_SOURCE_MUTATED = "source_mutated"
ORACLE_RESTORATION = "restoration"
ORACLE_REPEATABILITY = "repeatability"
ORACLE_ORDERING = "ordering_instability"
ORACLE_NO_GUESSING = "no_guessing"
ORACLE_WORKFLOW = "workflow_consistency"
ORACLE_ENGINE_DISAGREEMENT = "engine_disagreement"


@dataclass(frozen=True)
class TrialOutcome:
    """The full result of applying one operator to one record.

    Rich by design — this is the *internal* structure. It is NEVER projected
    into :func:`build_report`, which carries global scalars only.
    """

    operator_id: str
    category: str
    expected_outcome: str
    applicable: bool
    observed_valid: bool | None = None
    observed_error_count: int | None = None
    outcome_matched: bool | None = None
    oracle_failures: tuple[str, ...] = ()
    #: For category D: what the engine actually did, for reporting to a human.
    observation: str | None = None


def run_trial(
    record: Mapping[str, Any],
    operator: MutationOperator,
    root: Path,
    *,
    baseline: Evaluation | None = None,
    repeat: int = 3,
) -> TrialOutcome:
    """Apply one operator to one record and run every oracle.

    ``record`` is never modified; that is itself one of the oracles.
    """
    if repeat < 1:
        raise ValueError("repeat must be at least 1")

    if not operator.applicability(record):
        return TrialOutcome(
            operator_id=operator.operator_id,
            category=operator.category,
            expected_outcome=operator.expected_outcome,
            applicable=False,
        )

    # Snapshot BEFORE the lazy baseline, not after. Review finding: taking
    # `before` after `evaluate` means that on the `baseline=None` path — the
    # public default, exercised by several tests — a validator that mutated its
    # input would pollute `record` first, and both `source_unchanged` and
    # `no_guessing` would compare against the already-polluted state and go
    # blind. `run_harness` precomputes the baseline so the sweep was never
    # affected; the direct-call path was.
    before = canonical(record)

    if baseline is None:
        baseline = evaluate(record, root)
    originals = [
        (step, step.resolve(record), copy.deepcopy(_original_value(record, step)))
        for step in operator.steps
    ]

    clone = operator.apply(record)
    after = canonical(record)

    failures: list[str] = []
    if before != after or shares_container(record, clone):
        failures.append(ORACLE_SOURCE_MUTATED)

    clone_before_validation = canonical(clone)
    evaluations = [evaluate(clone, root) for _ in range(repeat)]
    if canonical(clone) != clone_before_validation:
        failures.append(ORACLE_NO_GUESSING)

    observed = evaluations[0]
    if not check_repeatability(evaluations):
        failures.append(ORACLE_REPEATABILITY)
    if not check_ordering_stable(evaluations):
        failures.append(ORACLE_ORDERING)
    if any(item.engines_disagree for item in evaluations):
        failures.append(ORACLE_ENGINE_DISAGREEMENT)

    # no_guessing: the validator populated nothing and corrected nothing.
    for step, concrete, _original in originals:
        if concrete is None:  # pragma: no cover - applicability already checked
            continue
        if step.op_kind == OP_REMOVE:
            if _resolve(step.path, clone) is not None:
                failures.append(ORACLE_NO_GUESSING)
        elif step.op_kind == OP_SET:
            resolved = _resolve(step.path, clone)
            if resolved is None or canonical(resolved[1]) != canonical(step.payload):
                failures.append(ORACLE_NO_GUESSING)
        elif step.op_kind == OP_INSERT_KEY:
            node = _node_at(clone, concrete)
            if not isinstance(node, dict) or step.payload not in node:
                failures.append(ORACLE_NO_GUESSING)

    # restoration: undo the DECLARED steps individually, in reverse order, in
    # the same clone that was just validated. Individually is what makes this
    # oracle failable: a wholesale `clone = deepcopy(record)` would restore any
    # clone whatsoever, including one that `apply` had damaged beyond its
    # declared steps. Re-validating afterwards is not redundant with the content
    # comparison: `official.load_official_validator` reads through an
    # `lru_cache`, so "the same bytes still evaluate to the baseline result" is
    # a claim about engine state, not only about the record.
    for step, concrete, original in reversed(originals):
        if concrete is None:  # pragma: no cover - applicability already checked
            continue
        if step.op_kind in (OP_REMOVE, OP_SET):
            _node_at(clone, concrete[:-1])[concrete[-1]] = copy.deepcopy(original)
        elif step.op_kind == OP_INSERT_KEY:
            node = _node_at(clone, concrete)
            if isinstance(node, dict):
                node.pop(step.payload, None)
    if canonical(clone) != before or evaluate(clone, root) != baseline:
        failures.append(ORACLE_RESTORATION)

    if not _workflow_consistent(observed.schema_valid):
        failures.append(ORACLE_WORKFLOW)

    matched: bool | None
    observation: str | None = None
    if operator.expected_outcome == EXPECT_INVALID:
        matched = not observed.schema_valid
        if matched and operator.category == CATEGORY_COMBINED:
            matched = len({item[0] for item in observed.signature}) >= 2
    elif operator.expected_outcome == EXPECT_VALID:
        matched = observed.schema_valid
        if operator.category == CATEGORY_OPTIONAL_REMOVAL:
            new_required = _required_pointers(observed) - _required_pointers(baseline)
            matched = matched and not new_required
    else:
        matched = None
        observation = "valid" if observed.schema_valid else "invalid"

    return TrialOutcome(
        operator_id=operator.operator_id,
        category=operator.category,
        expected_outcome=operator.expected_outcome,
        applicable=True,
        observed_valid=observed.schema_valid,
        observed_error_count=observed.error_count,
        outcome_matched=matched,
        oracle_failures=tuple(dict.fromkeys(failures)),
        observation=observation,
    )


def _original_value(record: Mapping[str, Any], step: MutationStep) -> Any:
    """The value a step will overwrite/remove (``None`` for ``insert_key``)."""
    if step.op_kind == OP_INSERT_KEY:
        return None
    resolved = _resolve(step.path, record)
    return None if resolved is None else resolved[1]


